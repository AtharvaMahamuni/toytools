// Character Map — the catalogue of characters the map renders.
//
// Data, not logic: the widget imports this at build time and prints a grid, so no character table
// ships in a script and no name is worked out in the browser. Names come from the Unicode standard,
// trimmed of the parts that read as noise in a picker ("Latin Small Letter E With Acute" is filed as
// "E With Acute", because the grid it sits in already says which alphabet you are looking at).
//
// `entity` holds the named HTML entity where one exists. Everything else falls back to the numeric
// form, which is derived rather than stored, since it is just the code point in hex.

export interface MapCharacter {
  /** The character itself. */
  char: string;
  /** Human-readable name, used for search and for the detail line. */
  name: string;
  /** Named HTML entity without the ampersand and semicolon, when the character has one. */
  entity?: string;
}

export interface CharacterGroup {
  /** Group heading, also the filter label. */
  name: string;
  /** One line saying what belongs in this group. */
  description: string;
  characters: MapCharacter[];
}

