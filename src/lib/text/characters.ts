/** The code point of a character, as U+XXXX. Astral characters are handled by codePointAt. */
export function codePoint(char: string): string {
  const cp = char.codePointAt(0) ?? 0;
  return `U+${cp.toString(16).toUpperCase().padStart(4, '0')}`;
}

/** The HTML entity to paste into markup: the named one when it exists, the numeric one otherwise. */
export function htmlEntity(c: MapCharacter): string {
  if (c.entity) return `&${c.entity};`;
  const cp = c.char.codePointAt(0) ?? 0;
  return `&#${cp};`;
}

/** The CSS content escape: a backslash, the hex code point, and a trailing space to end it. */
export function cssEscape(char: string): string {
  const cp = char.codePointAt(0) ?? 0;
  return `\\${cp.toString(16).toUpperCase()}`;
}

/** The JavaScript string escape, in the \u{...} form that covers every code point. */
export function jsEscape(char: string): string {
  const cp = char.codePointAt(0) ?? 0;
  return cp > 0xffff
    ? `\\u{${cp.toString(16).toUpperCase()}}`
    : `\\u${cp.toString(16).toUpperCase().padStart(4, '0')}`;
}
